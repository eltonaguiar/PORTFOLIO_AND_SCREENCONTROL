#!/usr/bin/env python3
"""Regenerate the live index inside TRACKING.md.

Deterministic and idempotent: reads the working tree, rewrites only the block between
`<!-- INDEX:START -->` and `<!-- INDEX:END -->`. No network, no git writes.

    python scripts/update_index.py            # update TRACKING.md in place
    python scripts/update_index.py --check    # exit 1 if TRACKING.md is stale

Designed to be run by a scheduler (cron/Task Scheduler) right after `git pull`.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRACKING = ROOT / "TRACKING.md"
START = "<!-- INDEX:START -->"
END = "<!-- INDEX:END -->"

TOPICS = [
    ("01-screen-control-llm", "Screen control via LLM/AI — how an agent sees and drives a machine"),
    ("02-portfolio-multi-asset", "Reference: tracking, engine choice, evidence rules"),
    ("03-trading-strategies", "The challenge: specs, rounds, results, ledgers"),
    ("REVIEWS", "Audits of model answers and challenge documents"),
]

SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv", ".pytest_cache"}
DATA_DIRS = {"results", "ledger", "state", "proof"}


def walk(base: Path):
    """Yield (path, size, lines) for tracked-looking files, skipping noise."""
    for p in sorted(base.rglob("*")):
        if p.is_dir():
            continue
        if any(part in SKIP_DIRS for part in p.parts):
            continue
        if p.suffix in {".pyc", ".pyo"}:
            continue
        try:
            size = p.stat().st_size
        except OSError:
            continue
        lines = ""
        if p.suffix in {".md", ".py", ".json", ".yml", ".yaml", ".jsonl"}:
            try:
                with p.open("r", encoding="utf-8", errors="ignore") as fh:
                    lines = str(sum(1 for _ in fh))
            except OSError:
                lines = ""
        yield p, size, lines


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def build_index() -> str:
    out: list[str] = []
    out.append("| Folder | Files | Artifacts (results/ledger/state) | Last commit |")
    out.append("|---|---:|---:|---|")
    for name, desc in TOPICS:
        base = ROOT / name
        if not base.exists():
            out.append(f"| `{name}/` | — | — | not created |")
            continue
        files = list(walk(base))
        docs = [f for f in files if f[0].suffix == ".md"]
        artifacts = [f for f in files if any(d in f[0].parts for d in DATA_DIRS)]
        out.append(
            f"| `{name}/` — {desc} | {len(files)} ({len(docs)} md) | {len(artifacts)} | "
            f"see `git log -1 -- {name}` |"
        )

    out.append("")
    out.append("### Documents")
    out.append("")
    out.append("| Path | Lines | Bytes |")
    out.append("|---|---:|---:|")
    for name, _ in TOPICS:
        base = ROOT / name
        if not base.exists():
            continue
        for p, size, lines in walk(base):
            if p.suffix != ".md":
                continue
            if any(d in p.parts for d in DATA_DIRS):
                continue
            out.append(f"| [`{rel(p)}`]({rel(p)}) | {lines} | {size} |")

    root_md = sorted(p for p in ROOT.glob("*.md") if p.name != TRACKING.name)
    if root_md:
        out.append("")
        out.append("### Top level")
        out.append("")
        out.append("| Path | Lines | Bytes |")
        out.append("|---|---:|---:|")
        for p in root_md:
            size = p.stat().st_size
            n = sum(1 for _ in p.open("r", encoding="utf-8", errors="ignore"))
            out.append(f"| [`{p.name}`]({p.name}) | {n} | {size} |")

    out.append("")
    out.append("_Generated by `scripts/update_index.py`; do not edit this block by hand._")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the index is stale")
    args = ap.parse_args()

    if not TRACKING.exists():
        print(f"missing {TRACKING}", file=sys.stderr)
        return 2

    text = TRACKING.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"markers {START} / {END} not found in TRACKING.md", file=sys.stderr)
        return 2

    index = build_index()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    updated = pattern.sub(lambda _: f"{START}\n{index}\n{END}", text)

    if updated == text:
        print("index up to date")
        return 0
    if args.check:
        print("index is stale — run: python scripts/update_index.py")
        return 1
    TRACKING.write_text(updated, encoding="utf-8")
    print(f"updated {TRACKING} ({len(index.splitlines())} index lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
